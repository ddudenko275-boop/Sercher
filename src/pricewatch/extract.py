"""Извлечение из текста объявления пробы 585 и веса в граммах.

Реальные объявления Авито обфусцируют текст латинскими буквами-двойниками
(«Пpоба», «Beс») и пишут вес без единицы («Вес: 4,77»). Поэтому:
  1) нормализуем гомоглифы (латиница → кириллица);
  2) ищем вес и по метке «вес/масса: N», и по «N г».
"""

from __future__ import annotations

import re

from . import config

# Латинские буквы-двойники → кириллица (продавцы так прячут текст от парсеров).
_LAT2CYR = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "y": "у", "x": "х", "k": "к",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
})


def _normalize(text: str) -> str:
    return (text or "").translate(_LAT2CYR)


# Вес по метке: «вес: 4,77», «масса 4.77» — единица не обязательна.
_WEIGHT_LABEL_RE = re.compile(
    r"(?:вес|масса)\W{0,3}(\d{1,4}(?:[.,]\d{1,2})?)",
    re.IGNORECASE,
)
# Вес по единице: «4,2 г», «4.2 гр», «4,2 грамма», «4.2 g».
_WEIGHT_UNIT_RE = re.compile(
    r"(\d{1,4}(?:[.,]\d{1,2})?)\s*(?:г|гр|грамм[а-я]*|g)(?![а-яёa-z])",
    re.IGNORECASE,
)

# Проба 585: число 585, не окружённое цифрами и не начало «585 000» (цены).
_PROBA_585_RE = re.compile(r"(?<!\d)585(?!\d)(?!\s\d{3})")


def has_proba_585(text: str) -> bool:
    """Есть ли в тексте признак 585 пробы."""
    return bool(_PROBA_585_RE.search(_normalize(text)))


# Признак «цена объявления указана ЗА ГРАММ» (лом/скупка): «цена за грамм»,
# «7250 за грамм», «стоимость грамма», «₽/г», «руб/грамм». Тогда делить на вес НЕ надо.
_PRICE_PER_GRAM_RE = re.compile(
    r"за\s*(?:1\s*)?грамм"
    r"|(?:цена|стоимост\w*)\s+(?:за\s+)?(?:1\s*)?грамма?"
    r"|(?:₽|руб|р)\s*/\s*(?:грамм|гр|г)\b",
    re.IGNORECASE,
)


def is_price_per_gram(text: str) -> bool:
    """Указана ли цена ЗА ГРАММ (тогда ₽/г = цена объявления, без деления на вес)."""
    return bool(_PRICE_PER_GRAM_RE.search(_normalize(text)))


# Вставки/камни — признак НЕ чистого золота (нужно исключать). Слова-корни, чтобы
# ловить любые формы: «с бриллиантом», «фианиты», «со вставками», «камни».
_STONES_RE = re.compile(
    r"бриллиант|брильянт|фианит|циркон|сапфир|изумруд|рубин|топаз|аметист"
    r"|гранат|жемчуг|цитрин|хризолит|перидот|шпинель|турмалин|танзанит|опал"
    r"|камн|камень|камен\w*|вставк|со\s+встав|самоцвет|кубическ\w*\s+цирконий"
    r"|swarovski|сваровски|эмал",
    re.IGNORECASE,
)
# «Без вставок/камней/бриллиантов» — это ОТСУТСТВИЕ камней, не считать наличием.
_NO_STONES_RE = re.compile(
    r"без\s+(?:вставок|вставк\w*|камн\w*|камен\w*|бриллиант\w*|фианит\w*|"
    r"брильянт\w*|циркон\w*|самоцвет\w*)",
    re.IGNORECASE,
)


def has_stones(text: str) -> bool:
    """Есть ли в изделии вставки/камни (тогда это НЕ чистое золото → исключаем).

    Сначала вырезаем отрицания «без вставок/камней», чтобы они не считались за
    наличие, затем ищем упоминание камней в остатке текста.
    """
    t = _normalize(text)
    t = _NO_STONES_RE.sub(" ", t)
    return bool(_STONES_RE.search(t))


def parse_weight_grams(text: str) -> tuple[float | None, bool]:
    """Вернуть (вес_в_граммах, неоднозначно?).

    Берём первое правдоподобное значение (сперва по метке «вес», затем по «N г»).
    Флаг «неоднозначно» — если правдоподобных значений несколько (цепь+подвеска).
    """
    t = _normalize(text)
    candidates: list[float] = []
    for regex in (_WEIGHT_LABEL_RE, _WEIGHT_UNIT_RE):
        for m in regex.finditer(t):
            try:
                w = float(m.group(1).replace(",", "."))
            except ValueError:
                continue
            if config.MIN_WEIGHT_G <= w <= config.MAX_WEIGHT_G:
                candidates.append(w)

    if not candidates:
        return None, False

    ambiguous = len(set(candidates)) > 1
    return candidates[0], ambiguous


# «Полная цена изделия» в тексте: 10 000…9 999 999. Ловим сгруппированные
# («250 000», «250.000») и слитные 5–7-значные. Разделители тысяч: пробел,
# неразрывный ( ) и узкий неразрывный ( ) пробелы, точка. Телефоны
# (11 цифр) и проба (585, < 10000) сюда не попадают — вне диапазона длины/значения.
_MONEY_SEP = "[   .]"
_MONEY_RE = re.compile(
    r"(?<![\d.,])(\d{1,3}(?:" + _MONEY_SEP + r"\d{3})+|\d{5,7})(?!\d)"
)


def parse_money_amounts(text: str) -> list[int]:
    """Все правдоподобные суммы (полные цены) из текста, 10 000…9 999 999 ₽.

    Нужно для перекрёстной проверки: если цена_объявления × вес ≈ одной из этих
    сумм, значит в цене объявления указан ₽/ГРАММ (а не полная цена изделия).
    """
    out: list[int] = []
    for m in _MONEY_RE.finditer(_normalize(text)):
        digits = re.sub(_MONEY_SEP, "", m.group(1))
        try:
            val = int(digits)
        except ValueError:
            continue
        if 10_000 <= val <= 9_999_999:
            out.append(val)
    return out
